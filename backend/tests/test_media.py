class MediaStoreTests(unittest.TestCase):
    def setUp(self):
        self.tmp = TemporaryDirectory()
        self.old = media.MEDIA_DIR
        media.MEDIA_DIR = Path(self.tmp.name)

    def tearDown(self):
        media.MEDIA_DIR = self.old
        self.tmp.cleanup()

    def test_roundtrip_jpeg(self):
        import base64

        uri = "data:image/jpeg;base64," + base64.b64encode(_tiny_jpeg()).decode("ascii")
        saved = media.save_data_uri(uri)
        self.assertTrue(media.valid_id(saved["id"]))
        blob = media.load_bytes(saved["id"])
        self.assertEqual(blob[:2], b"\xff\xd8")
        self.assertEqual(blob[-2:], b"\xff\xd9")

    def test_rejects_png_uri(self):
        with self.assertRaises(ValueError):
            media.save_data_uri("data:image/png;base64,aaaa")

    def test_rejects_bad_id(self):
        self.assertIsNone(media.load_bytes("../etc/passwd"))
        self.assertIsNone(media.load_bytes("not-a-uuid"))


